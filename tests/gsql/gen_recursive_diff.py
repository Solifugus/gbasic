#!/usr/bin/env python3
# WITH RECURSIVE differential (docs/gsql_recursive_design.md §6): random
# directed graphs, cycles and self-loops included, and random recursive
# queries, each answer computed by SQLite's WITH RECURSIVE and written as a
# tests/gsql/sql_test.c script. Every query reading the recursive one orders
# by all its columns, so the comparison is of the whole multiset of rows.
#
#   gen_recursive_diff.py SEED QUERIES OUT
#
# SQLite has no CYCLE clause, so for the CYCLE form SQLite is given the rule
# written out by hand, a route as text ',1,4,' and a mark from instr(), which
# is a second formulation of the rule, not G-SQL's. A census floor fails the
# generator when a form, or a graph with a cycle, was too rarely drawn.
import random
import sqlite3
import sys

seed, nq, out = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
rnd = random.Random(seed)

nodes = rnd.randint(3, 9)
edges = []
for i in range(rnd.randint(nodes, nodes * 2)):
    edges.append((i + 1, rnd.randint(1, nodes), rnd.randint(1, nodes), rnd.randint(1, 9)))
# and one edge reversed, so every graph has a cycle for UNION and CYCLE to meet
_, s0, d0, _ = edges[rnd.randrange(len(edges))]
edges.append((len(edges) + 1, d0, s0, rnd.randint(1, 9)))
labels = [(i, rnd.randint(1, 3)) for i in range(1, nodes + 1)]

db = sqlite3.connect(":memory:")
db.execute("CREATE TABLE e (id INTEGER PRIMARY KEY, src INTEGER, dst INTEGER, w INTEGER)")
db.execute("CREATE TABLE n (id INTEGER PRIMARY KEY, label INTEGER)")
db.executemany("INSERT INTO e VALUES (?, ?, ?, ?)", edges)
db.executemany("INSERT INTO n VALUES (?, ?)", labels)

census = {}
def count(k):
    census[k] = census.get(k, 0) + 1

# does the graph have a cycle? (a depth-first search for a back edge)
adj = {}
for _, s, d, _ in edges:
    adj.setdefault(s, []).append(d)
state = {}
def cyclic(v):
    state[v] = 1
    for d in adj.get(v, []):
        if state.get(d) == 1 or (d not in state and cyclic(d)):
            return True
    state[v] = 2
    return False
if any(v not in state and cyclic(v) for v in range(1, nodes + 1)):
    count("cyclic graph")

lines = ["# generated by tests/gsql/gen_recursive_diff.py %d %d; answers computed by SQLite %s" %
         (seed, nq, sqlite3.sqlite_version)]
def case(sql, answer):
    lines.append("> " + sql)
    lines.append("= " + answer)

case("CREATE TABLE e (id INTEGER PRIMARY KEY, src INTEGER, dst INTEGER, w INTEGER)", "done 0")
case("CREATE TABLE n (id INTEGER PRIMARY KEY, label INTEGER)", "done 0")
case("INSERT INTO e VALUES " + ", ".join("(%d, %d, %d, %d)" % r for r in edges), "done %d" % len(edges))
case("INSERT INTO n VALUES " + ", ".join("(%d, %d)" % r for r in labels), "done %d" % len(labels))

def render(v):
    return "NULL" if v is None else str(v)

def one():
    s = rnd.randint(1, nodes)
    depth = rnd.randint(1, 5)
    wmin = rnd.randint(0, 6)
    form = rnd.choice(["reach", "reach_from_edges", "bounded_all", "bounded_union", "weights", "label_join",
                       "self_second", "series", "two_anchors", "cycle"])
    count(form)
    filt = " AND e.w > %d" % wmin if rnd.random() < 0.3 else ""
    if form == "reach":
        body = ("SELECT %d UNION SELECT e.dst FROM r JOIN e ON e.src = r.x WHERE 1 = 1%s" % (s, filt))
        return "WITH RECURSIVE r (x) AS (%s) SELECT x FROM r ORDER BY x" % body, None
    if form == "reach_from_edges":
        body = ("SELECT dst FROM e WHERE src = %d UNION SELECT e.dst FROM r JOIN e ON e.src = r.x" % s)
        return "WITH RECURSIVE r (x) AS (%s) SELECT x FROM r ORDER BY x" % body, None
    if form == "bounded_all":
        body = ("SELECT %d, 0 UNION ALL SELECT e.dst, r.d + 1 FROM r JOIN e ON e.src = r.x WHERE r.d < %d%s" %
                (s, depth, filt))
        return "WITH RECURSIVE r (x, d) AS (%s) SELECT x, d FROM r ORDER BY x, d" % body, None
    if form == "bounded_union":
        body = ("SELECT %d, 0 UNION SELECT e.dst, r.d + 1 FROM r JOIN e ON e.src = r.x WHERE r.d < %d" %
                (s, depth))
        return "WITH RECURSIVE r (x, d) AS (%s) SELECT x, d FROM r ORDER BY x, d" % body, None
    if form == "weights":
        body = ("SELECT %d, 0, 0 UNION ALL SELECT e.dst, r.t + e.w, r.d + 1 FROM r JOIN e ON e.src = r.x "
                "WHERE r.d < %d" % (s, depth))
        return ("WITH RECURSIVE r (x, t, d) AS (%s) SELECT x, count(*), sum(t), min(t), max(d) FROM r GROUP BY x "
                "ORDER BY x" % body), None
    if form == "label_join":
        body = ("SELECT %d, 0 UNION SELECT e.dst, n.label FROM r JOIN e ON e.src = r.x JOIN n ON n.id = e.dst "
                "WHERE n.label <> 2" % s)
        return "WITH RECURSIVE r (x, l) AS (%s) SELECT x, l FROM r ORDER BY x, l" % body, None
    if form == "self_second":
        body = ("SELECT %d, 0 UNION ALL SELECT e.dst, r.d + 1 FROM e JOIN r ON e.src = r.x WHERE r.d < %d" %
                (s, depth))
        return "WITH RECURSIVE r (x, d) AS (%s) SELECT x, d FROM r ORDER BY x, d" % body, None
    if form == "series":
        k = rnd.randint(1, 60)
        body = "SELECT 1 UNION ALL SELECT i + 1 FROM c WHERE i < %d" % k
        return "WITH RECURSIVE c (i) AS (%s) SELECT count(*), sum(i), max(i) FROM c" % body, None
    if form == "two_anchors":
        s2 = rnd.randint(1, nodes)
        body = ("SELECT %d UNION SELECT %d UNION SELECT e.dst FROM r JOIN e ON e.src = r.x" % (s, s2))
        return "WITH RECURSIVE r (x) AS (%s) SELECT x FROM r ORDER BY x" % body, None
    # cycle: G-SQL's CYCLE clause against the rule written out for SQLite
    gs = ("WITH RECURSIVE r (x, d) AS (SELECT %d, 0 UNION ALL SELECT e.dst, r.d + 1 FROM r JOIN e ON e.src = r.x) "
          "CYCLE x SET looped USING route SELECT x, d, looped FROM r ORDER BY x, d, looped" % s)
    lite = ("WITH RECURSIVE r (x, d, route, looped) AS (SELECT %d, 0, ',%d,', 0 UNION ALL "
            "SELECT e.dst, r.d + 1, r.route || e.dst || ',', instr(r.route, ',' || e.dst || ',') > 0 "
            "FROM r JOIN e ON e.src = r.x WHERE NOT r.looped) "
            "SELECT x, d, CASE WHEN looped THEN 'TRUE' ELSE 'FALSE' END FROM r ORDER BY x, d, looped" % (s, s))
    return gs, lite

for q in range(nq):
    gsql, lite = one()
    got = db.execute(lite or gsql).fetchall()
    case(gsql, " | ".join(", ".join(render(v) for v in r) for r in got) if got else "(none)")

floor = {"reach": 3, "reach_from_edges": 3, "bounded_all": 3, "bounded_union": 3, "weights": 3, "label_join": 3,
         "self_second": 3, "series": 3, "two_anchors": 3, "cycle": 3, "cyclic graph": 1}
short = [k for k, n in floor.items() if census.get(k, 0) < n]
open(out, "w").write("\n".join(lines) + "\n")
print("census: " + ", ".join("%s %d" % (k, census.get(k, 0)) for k in sorted(floor)))
if short:
    print("census below its floor: " + ", ".join(short))
    sys.exit(2)
