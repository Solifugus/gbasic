#!/usr/bin/env python3
# Window functions differential (docs/gsql_window_design.md §6): random rows
# and random windows, each answer computed by SQLite -- an implementation of
# window functions that is not G-SQL's -- and written as a tests/gsql/sql_test.c
# script, so the answers are no one's guess and none of them G-SQL's own.
#
#   gen_window_diff.py SEED QUERIES OUT
#
# Where SQL leaves an answer to the implementation, the query pins it:
#   - NULLs: G-SQL sorts NULL last ascending and first descending, so every
#     ORDER BY written for SQLite says so (NULLS LAST / NULLS FIRST);
#   - ties: a function whose answer depends on the order of peers (row_number,
#     ntile, lag, lead, a ROWS frame, first_value and the like) gets `id`
#     appended to its window's ORDER BY, so there are no peers to order. Rank,
#     dense_rank, percent_rank and cume_dist, and an aggregate over a RANGE or
#     default frame, depend only on the peer groups, so those keep their ties:
#     that is where peers are tested.
# A census floor fails the generator when a function, a frame kind or
# partitioning was too rarely drawn, so a drift to trivial windows cannot pass.
import random
import sqlite3
import sys

if sqlite3.sqlite_version_info < (3, 30, 0):
    print("SKIP: SQLite %s has no NULLS LAST (3.30 needed)" % sqlite3.sqlite_version)
    sys.exit(3)

seed, nq, out = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
rnd = random.Random(seed)

def maybe_null(v, p=0.15):
    return None if rnd.random() < p else v

nrows = rnd.randint(1, 40)
rows = [(i, maybe_null(rnd.randint(1, 4)), maybe_null(rnd.randint(1, 3)), maybe_null(rnd.randint(1, 6)),
         maybe_null(rnd.randint(-20, 50))) for i in range(1, nrows + 1)]
COLS = ["g", "h", "o", "v"]

db = sqlite3.connect(":memory:")
db.execute("CREATE TABLE t (id INTEGER PRIMARY KEY, g INTEGER, h INTEGER, o INTEGER, v INTEGER)")
db.executemany("INSERT INTO t VALUES (?, ?, ?, ?, ?)", rows)

lines = ["# generated by tests/gsql/gen_window_diff.py %d %d; answers computed by SQLite %s" %
         (seed, nq, sqlite3.sqlite_version)]
def case(sql, answer):
    lines.append("> " + sql)
    lines.append("= " + answer)

def lit(v):
    return "NULL" if v is None else str(v)

case("CREATE TABLE t (id INTEGER PRIMARY KEY, g INTEGER, h INTEGER, o INTEGER, v INTEGER)", "done 0")
case("INSERT INTO t VALUES " + ", ".join("(%s)" % ", ".join(lit(x) for x in r) for r in rows), "done %d" % len(rows))

census = {}
def count(k):
    census[k] = census.get(k, 0) + 1

PEER_ONLY = {"rank", "dense_rank", "percent_rank", "cume_dist"}
FRAMED = {"first_value", "last_value", "nth_value", "count", "sum", "avg", "min", "max"}

def bound(start):
    kinds = ["UNBOUNDED PRECEDING", "n PRECEDING", "CURRENT ROW", "n FOLLOWING", "UNBOUNDED FOLLOWING"]
    return rnd.choice(kinds[:4] if start else kinds[1:])

def frame():
    """a valid frame (G-SQL's text, SQLite's text), or None for the default"""
    r = rnd.random()
    if r < 0.3:
        return None, "default"
    if r < 0.45:
        s = rnd.choice(["UNBOUNDED PRECEDING", "CURRENT ROW"])
        e = rnd.choice(["CURRENT ROW", "UNBOUNDED FOLLOWING"])
        if s == "CURRENT ROW" and e == "CURRENT ROW" and rnd.random() < 0.5:
            e = "UNBOUNDED FOLLOWING"
        return "RANGE BETWEEN %s AND %s" % (s, e), "range"
    order = ["UNBOUNDED PRECEDING", "n PRECEDING", "CURRENT ROW", "n FOLLOWING", "UNBOUNDED FOLLOWING"]
    while True:
        s, e = bound(True), bound(False)
        if order.index(s) <= order.index(e):
            break
    s = s.replace("n", str(rnd.randint(0, 3)), 1) if s[0] == "n" else s
    e = e.replace("n", str(rnd.randint(0, 3)), 1) if e[0] == "n" else e
    return "ROWS BETWEEN %s AND %s" % (s, e), "rows"

def window(fn):
    parts = []
    if rnd.random() < 0.6:
        parts = rnd.sample(["g", "h"], rnd.randint(1, 2))
        count("partitioned")
    terms = [(c, rnd.random() < 0.4) for c in rnd.sample(["o", "h", "v"], rnd.randint(0, 2))]
    fr, kind = (None, "none")
    if fn in FRAMED:
        fr, kind = frame()
        count("frame " + kind)
    exact = fn in PEER_ONLY or (fn in {"count", "sum", "avg", "min", "max"} and kind in ("default", "range"))
    if not exact:
        terms.append(("id", rnd.random() < 0.5))
    def text(sqlite):
        w = []
        if parts:
            w.append("PARTITION BY " + ", ".join(parts))
        if terms:
            w.append("ORDER BY " + ", ".join(
                c + (" DESC" if d else "") + ((" NULLS FIRST" if d else " NULLS LAST") if sqlite else "")
                for c, d in terms))
        if fr:
            w.append(fr)
        return " OVER (" + " ".join(w) + ")"
    return text(False), text(True)

def call():
    fn = rnd.choice(["row_number", "rank", "dense_rank", "percent_rank", "cume_dist", "ntile", "lag", "lead",
                     "first_value", "last_value", "nth_value", "count", "count(*)", "sum", "avg", "min", "max"])
    count(fn)
    col = rnd.choice(COLS)
    if fn == "count(*)":
        name, args = "count", "*"
        fn = "count"
    elif fn in ("row_number", "rank", "dense_rank", "percent_rank", "cume_dist"):
        name, args = fn, ""
    elif fn == "ntile":
        name, args = fn, str(rnd.randint(1, 5))
    elif fn in ("lag", "lead"):
        name = fn
        a = [col]
        if rnd.random() < 0.7:
            a.append(str(rnd.randint(0, 3)))
            if rnd.random() < 0.5:
                a.append(str(rnd.randint(-5, 5)))
        args = ", ".join(a)
    elif fn == "nth_value":
        name, args = fn, "%s, %d" % (col, rnd.randint(1, 3))
    else:
        name, args = fn, col
    g, s = window(fn)
    return "%s(%s)%s" % (name, args, g), "%s(%s)%s" % (name, args, s)

def render(v):
    if v is None:
        return "NULL"
    if isinstance(v, float):
        # as tests/gsql/sql_test.c renders an inexact number: the shortest
        # %g that reads back, so 50.0 is `5e+01`, and `.0` where it has no mark
        for prec in range(1, 18):
            t = "%.*g" % (prec, v)
            if float(t) == v:
                break
        return t if any(ch in t for ch in ".eEni") else t + ".0"
    return str(v)

for q in range(nq):
    calls = [call() for _ in range(rnd.randint(1, 4))]
    where = ""
    if rnd.random() < 0.2:
        where = " WHERE v > %d" % rnd.randint(-10, 30)
    gsql = "SELECT id, " + ", ".join(c[0] for c in calls) + " FROM t" + where + " ORDER BY id"
    lite = "SELECT id, " + ", ".join(c[1] for c in calls) + " FROM t" + where + " ORDER BY id"
    got = db.execute(lite).fetchall()
    case(gsql, " | ".join(", ".join(render(v) for v in r) for r in got) if got else "(none)")

floor = {k: 3 for k in ["row_number", "rank", "dense_rank", "percent_rank", "cume_dist", "ntile", "lag", "lead",
                        "first_value", "last_value", "nth_value", "count", "count(*)", "sum", "avg", "min", "max"]}
floor.update({"frame default": 10, "frame rows": 10, "frame range": 5, "partitioned": 20})
short = [k for k, n in floor.items() if census.get(k, 0) < n]
open(out, "w", newline="\n", encoding="utf-8").write("\n".join(lines) + "\n")
print("census: " + ", ".join("%s %d" % (k, census.get(k, 0)) for k in sorted(floor)))
if short:
    print("census below its floor: " + ", ".join(short))
    sys.exit(2)
