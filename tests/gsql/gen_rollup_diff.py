#!/usr/bin/env python3
# Grouping sets differential (docs/gsql_rollup_design.md §5): random rows and
# random GROUP BY elements (expressions, ROLLUP, CUBE, GROUPING SETS), each
# answer computed by SQLite from what the sets MEAN -- the UNION ALL of one
# plain GROUP BY per set, a left-out column NULL and GROUPING's bits written
# as constants -- and written as a tests/gsql/sql_test.c script. SQLite has no
# ROLLUP, so this is the definition spelled out, not another implementation of
# the shortcut. Both sides order by every output column, NULLs last.
#
#   gen_rollup_diff.py SEED QUERIES OUT
import itertools
import random
import sqlite3
import sys

seed, nq, out = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
rnd = random.Random(seed)

def maybe_null(v, p=0.15):
    return None if rnd.random() < p else v

nrows = rnd.randint(0, 30)
rows = [(i, maybe_null(rnd.randint(1, 3)), maybe_null(rnd.randint(1, 3)), maybe_null(rnd.randint(1, 2)),
         maybe_null(rnd.randint(-10, 20))) for i in range(1, nrows + 1)]
COLS = ["a", "b", "c"]

db = sqlite3.connect(":memory:")
db.execute("CREATE TABLE t (id INTEGER PRIMARY KEY, a INTEGER, b INTEGER, c INTEGER, v INTEGER)")
db.executemany("INSERT INTO t VALUES (?, ?, ?, ?, ?)", rows)

lines = ["# generated by tests/gsql/gen_rollup_diff.py %d %d; answers computed by SQLite %s" %
         (seed, nq, sqlite3.sqlite_version)]
def case(sql, answer):
    lines.append("> " + sql)
    lines.append("= " + answer)

def lit(v):
    return "NULL" if v is None else str(v)

case("CREATE TABLE t (id INTEGER PRIMARY KEY, a INTEGER, b INTEGER, c INTEGER, v INTEGER)", "done 0")
if rows:
    case("INSERT INTO t VALUES " + ", ".join("(%s)" % ", ".join(lit(x) for x in r) for r in rows), "done %d" % len(rows))

census = {}
def count(k):
    census[k] = census.get(k, 0) + 1

def element():
    """(G-SQL text, list of sets, each a frozenset of column names)"""
    kind = rnd.choice(["plain", "rollup", "cube", "sets"])
    count(kind)
    if kind == "plain":
        c = rnd.choice(COLS)
        return c, [frozenset([c])]
    if kind in ("rollup", "cube"):
        cs = rnd.sample(COLS, rnd.randint(1, 3))
        if kind == "rollup":
            sets = [frozenset(cs[:n]) for n in range(len(cs), -1, -1)]
        else:
            sets = [frozenset(s) for n in range(len(cs) + 1) for s in itertools.combinations(cs, n)]
        return "%s(%s)" % (kind.upper(), ", ".join(cs)), sets
    sets, texts = [], []
    for _ in range(rnd.randint(1, 3)):
        cs = rnd.sample(COLS, rnd.randint(0, 2))
        sets.append(frozenset(cs))
        texts.append("(" + ", ".join(cs) + ")")
    return "GROUPING SETS (%s)" % ", ".join(texts), sets

def render(v):
    return "NULL" if v is None else str(v)

for q in range(nq):
    elems = [element() for _ in range(rnd.randint(1, 2))]
    sets = [frozenset()]
    for _, es in elems:
        sets = [s | e for s in sets for e in es]
    named = []
    for col in COLS:
        if any(col in s for _, es in elems for s in es):
            named.append(col)
    where = " WHERE v > %d" % rnd.randint(-5, 10) if rnd.random() < 0.3 else ""
    aggs = ["count(*)", "sum(v)", "min(v)", "max(a)"]
    rnd.shuffle(aggs)
    aggs = aggs[:rnd.randint(1, 3)]
    outs = named + (["GROUPING(%s)" % ", ".join(named)] if named else []) + aggs
    order = " ORDER BY " + ", ".join(str(i + 1) for i in range(len(outs)))
    gsql = ("SELECT " + ", ".join(outs) + " FROM t" + where + " GROUP BY " + ", ".join(t for t, _ in elems) + order)
    parts = []
    for s in sets:
        bits = 0
        for col in named:
            bits = bits << 1 | (col not in s)
        sel = [col if col in s else "NULL" for col in named] + ([str(bits)] if named else []) + aggs
        grp = " GROUP BY " + ", ".join(c for c in named if c in s) if s else ""
        parts.append("SELECT " + ", ".join(sel) + " FROM t" + where + grp)
    lite = (" UNION ALL ".join(parts) + " ORDER BY " +
            ", ".join("%d NULLS LAST" % (i + 1) for i in range(len(outs))))
    if len(sets) > 1:
        count("several sets")
    if any(len(s) == 0 for s in sets):
        count("an empty set")
    got = db.execute(lite).fetchall()
    case(gsql, " | ".join(", ".join(render(v) for v in r) for r in got) if got else "(none)")

floor = {"plain": 5, "rollup": 5, "cube": 5, "sets": 5, "several sets": 20, "an empty set": 10}
short = [k for k, n in floor.items() if census.get(k, 0) < n]
open(out, "w", newline="\n", encoding="utf-8").write("\n".join(lines) + "\n")
print("census: " + ", ".join("%s %d" % (k, census.get(k, 0)) for k in sorted(floor)))
if short:
    print("census below its floor: " + ", ".join(short))
    sys.exit(2)
