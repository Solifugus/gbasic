#!/usr/bin/env python3
"""Generates src/term_widths.h: how many terminal cells a codepoint takes
(docs/tui_design.md §2.2), from the Unicode Character Database files in
UCD_DIR (default /usr/share/unicode, Debian's unicode-data package).

    python3 -I tools/make_term_widths.py [UCD_DIR] > src/term_widths.h

Pinned: the version is read from EastAsianWidth.txt's first line, written
into the header, and must be EXPECT below, so a newer UCD changes the table
only when someone moves the pin. Rules, in order:
  - C0 and C1 controls and DEL are not printable (the layer refuses them);
  - width 0: general category Mn, Me or Cf (but U+00AD SOFT HYPHEN and the
    prepended concatenation marks, which are drawn, are 1),
    Hangul medial vowels and final consonants U+1160..U+11FF and
    U+D7B0..U+D7FF (they join the syllable before them), and U+200B;
  - width 2: East Asian Width W or F;
  - otherwise 1. Ambiguous (A) is 1, as terminals draw it outside CJK locales.
Terminals disagree on some of these (an emoji turned to presentation by
U+FE0F, some ambiguous characters); the reference says so."""
import os, sys

EXPECT = '16.0.0'
ucd = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/unicode'

def ranges(path):
    for line in open(os.path.join(ucd, path), encoding='utf-8'):
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        cps, value = [x.strip() for x in line.split(';')[:2]]
        lo, _, hi = cps.partition('..')
        yield int(lo, 16), int(hi or lo, 16), value

first = open(os.path.join(ucd, 'EastAsianWidth.txt'), encoding='utf-8').readline()
version = first.strip().split('-')[-1].replace('.txt', '')
if version != EXPECT:
    sys.exit('make_term_widths: %s holds Unicode %s; the pin is %s' % (ucd, version, EXPECT))

width = {}
for lo, hi, v in ranges('EastAsianWidth.txt'):
    if v in ('W', 'F'):
        for cp in range(lo, hi + 1):
            width[cp] = 2
# UnicodeData.txt: ranges are written as <..., First> / <..., Last> pairs
start = None
for line in open(os.path.join(ucd, 'UnicodeData.txt'), encoding='utf-8'):
    f = line.split(';')
    cp, name, cat = int(f[0], 16), f[1], f[2]
    if name.endswith(', First>'):
        start = cp
        continue
    lo = start if name.endswith(', Last>') else cp
    start = None
    if cat in ('Mn', 'Me', 'Cf') and cp != 0x00AD:
        for c in range(lo, cp + 1):
            width[c] = 0
for lo, hi in ((0x1160, 0x11FF), (0xD7B0, 0xD7FF), (0x200B, 0x200B)):
    for c in range(lo, hi + 1):
        width[c] = 0
# A prepended concatenation mark (U+0600 ARABIC NUMBER SIGN...) is a format
# character that is DRAWN, spanning the digits after it: one cell
for lo, hi, v in ranges('PropList.txt'):
    if v == 'Prepended_Concatenation_Mark':
        for c in range(lo, hi + 1):
            width.pop(c, None)

def runs(w):
    out = []
    for cp in sorted(c for c in width if width[c] == w):
        if out and out[-1][1] == cp - 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out

print('/* Generated by tools/make_term_widths.py from the Unicode Character')
print(' * Database %s. Do not edit: change the generator and run it again. */' % version)
print('#define TERM_WIDTHS_UNICODE "%s"' % version)
for w, name in ((0, 'zero'), (2, 'wide')):
    r = runs(w)
    print('static const unsigned int term_width_%s[][2] = {' % name)
    for i in range(0, len(r), 4):
        print('    ' + ' '.join('{ 0x%05X, 0x%05X },' % (a, b) for a, b in r[i:i + 4]))
    print('};')
    print('#define TERM_WIDTH_%s_COUNT %d' % (name.upper(), len(r)))
