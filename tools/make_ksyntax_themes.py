#!/usr/bin/env python3
"""Write src/ksyntax_themes.h: KDE's own syntax-highlighting themes, which its
library carries compiled in, so the terminal's editor has the same names and
colours Qt's has (docs/tui_design.md §3.9).

    tools/make_ksyntax_themes.py DIR > src/ksyntax_themes.h

DIR holds the .theme files tests/ui_tui/ksh_probe.cpp extracts from the
library (`ksh_probe extract DIR` writes DIR/themes). The themes are KDE's,
under the MIT licence their files carry.

ONLY WHAT THE TERMINAL DRAWS WITH, PACKED, because the themes as JSON would
be a twelfth of the binary (measured: 250 KB against 3 MB of text). Kept: a
theme's name and revision, each text style's colour, background and four
flags, its editor colours, and its styles for a definition's items, whose
(definition, item) names are shared by every theme (470 names, 3682 uses).
Each style is 8 bytes: what it has (1 colour, 2 background), the colour and
the background as three bytes each, then the flags, two bits each from the
low end for bold, italic, underline and strike-through (0 unset, 1 off, 2 on).
tests/run_ui_tui.sh's `syntax` tier holds every theme here to KDE's library.
"""
import json
import os
import sys

STYLES = ["Normal", "Keyword", "Function", "Variable", "ControlFlow", "Operator", "BuiltIn", "Extension",
          "Preprocessor", "Attribute", "Char", "SpecialChar", "String", "VerbatimString", "SpecialString",
          "Import", "DataType", "DecVal", "BaseN", "Float", "Constant", "Comment", "Documentation", "Annotation",
          "CommentVar", "RegionMarker", "Information", "Warning", "Alert", "Others", "Error"]


def colour(v):
    if not isinstance(v, str) or not v.startswith('#'):
        return None
    h = v[1:].lower()
    if len(h) == 3:
        h = ''.join(c * 2 for c in h)
    if len(h) == 8:
        h = h[2:]
    return int(h, 16) if len(h) == 6 else None


def pack(st):
    fg, bg = colour(st.get('text-color')), colour(st.get('background-color'))
    has = (1 if fg is not None else 0) | (2 if bg is not None else 0)
    fl = 0
    for i, k in enumerate(('bold', 'italic', 'underline', 'strike-through')):
        v = st.get(k)
        if isinstance(v, bool):
            fl |= (2 if v else 1) << (2 * i)
    fg, bg = fg or 0, bg or 0
    return [has, fg >> 16, (fg >> 8) & 255, fg & 255, bg >> 16, (bg >> 8) & 255, bg & 255, fl]


def cstr(s):
    out = ''
    for b in s.encode('utf-8'):
        out += chr(b) if 0x20 <= b < 0x7f and chr(b) not in '"\\' else '\\%03o' % b
    return '"%s"' % out


def rows(nums):
    lines = []
    for i in range(0, len(nums), 16):
        lines.append('    ' + ', '.join(str(n) for n in nums[i:i + 16]) + ',')
    return '\n'.join(lines)


def main():
    d = os.path.join(sys.argv[1], 'themes')
    files = sorted(f for f in os.listdir(d) if f.endswith('.theme'))
    themes = [(f, json.load(open(os.path.join(d, f), encoding='utf-8'))) for f in files]
    roles = sorted({r for _, t in themes for r in t.get('editor-colors', {})})
    keys = sorted({(dn, k) for _, t in themes for dn, items in t.get('custom-styles', {}).items() for k in items})
    index = {k: i for i, k in enumerate(keys)}
    print('/* GENERATED by tools/make_ksyntax_themes.py from KDE\'s KSyntaxHighlighting')
    print(' * themes (MIT licence); do not edit. The packing is that script\'s. */')
    print('static const char *const ksh_roles[] = {%s};' % ', '.join(cstr(r) for r in roles))
    print('static const char *const ksh_custom_def[] = {')
    print('\n'.join('    %s,' % cstr(dn) for dn, _ in keys))
    print('};')
    print('static const char *const ksh_custom_item[] = {')
    print('\n'.join('    %s,' % cstr(k) for _, k in keys))
    print('};')
    for n, (f, t) in enumerate(themes):
        styles = []
        for s in STYLES:
            styles += pack(t.get('text-styles', {}).get(s, {}))
        ed = []
        for r, v in t.get('editor-colors', {}).items():
            c = colour(v)
            if c is not None:
                ed += [roles.index(r), c >> 16, (c >> 8) & 255, c & 255]
        cs = []
        for dn, items in t.get('custom-styles', {}).items():
            for k, st in items.items():
                p = pack(st)
                if p[0] or p[7]:
                    i = index[(dn, k)]
                    cs += [i >> 8, i & 255] + p
        print('static const unsigned char ksh_theme%d_styles[] = {\n%s\n};' % (n, rows(styles)))
        print('static const unsigned char ksh_theme%d_editor[] = {\n%s\n};' % (n, rows(ed or [0])))
        print('static const unsigned char ksh_theme%d_custom[] = {\n%s\n};' % (n, rows(cs or [0])))
    print('static const struct {')
    print('    const char *file, *name;')
    print('    int revision;')
    print('    const unsigned char *styles, *editor, *custom;')
    print('    unsigned neditor, ncustom;')
    print('} ksh_builtin_themes[] = {')
    for n, (f, t) in enumerate(themes):
        meta = t['metadata']
        ne = sum(1 for v in t.get('editor-colors', {}).values() if colour(v) is not None)
        nc = sum(1 for items in t.get('custom-styles', {}).values() for st in items.values()
                 if (lambda p: p[0] or p[7])(pack(st)))
        print('    {%s, %s, %d, ksh_theme%d_styles, ksh_theme%d_editor, ksh_theme%d_custom, %d, %d},'
              % (cstr(f), cstr(meta['name']), int(meta.get('revision', 0)), n, n, n, ne, nc))
    print('};')


main()
